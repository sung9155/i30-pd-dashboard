#!/usr/bin/env python3
"""Generate shared/src/com/veloster/vehicle/TaxiZoneData.java: the taxi business areas (사업구역) the meter tells apart.

Source: vuski/admdongkor sgg_<date>.parquet (시군구 boundaries, EPSG:5179), itself derived from Statistics Korea SGIS
(KOGL Type 1, CC BY 4.0 for the modifications). Needs shapely, pyarrow and pyproj (a throwaway venv is fine):

    python scripts/taxi_zones.py sgg_20261001.parquet

One zone per special / metropolitan city and Sejong and Jeju (the whole city or island is one fare area), one per 시 or 군
in the provinces (일반구 merged into their 시). Since the 2026 merger the old Gwangju districts sit in 전남광주통합특별시;
the fare table still lists 광주 and 전남 apart, so those five 구 become the 광주 zone. Rings are simplified to SIMPLIFY_M
and coded as Google polyline strings (1e-5 degrees), one string per zone with the rings separated by spaces.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

import pyarrow.parquet as pq
import shapely
from pyproj import Transformer
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "shared/src/com/veloster/vehicle/TaxiZoneData.java"
SIMPLIFY_M = 200
MIN_PART_M2 = 3e6   # islands smaller than this are dropped (a zone keeps at least its biggest part)
# Fare-table name (TaxiTariff) per 시도 code; metropolitan ones are one zone each.
WHOLE = {"11": "서울", "26": "부산", "27": "대구", "28": "인천", "30": "대전", "31": "울산", "36": "세종", "50": "제주"}
PROVINCE = {"41": "경기", "51": "강원", "43": "충북", "44": "충남", "52": "전북", "47": "경북", "48": "경남", "12": "전남"}
GWANGJU = {"12210", "12240", "12270", "12300", "12330"}   # 동구 서구 남구 북구 광산구 of the old 광주광역시


def zone_of(row):
    sido, code, name = row["sidocd"], row["sggcd"], row["sggnm"]
    if sido in WHOLE:
        return WHOLE[sido], WHOLE[sido]
    if code in GWANGJU:
        return "광주", "광주"
    m = re.match(r"^(\S+?시)\S+구$", name)   # 수원시장안구 -> 수원시
    return PROVINCE[sido], m.group(1) if m else name


def polyline(points):
    out, plat, plon = [], 0, 0
    for lon, lat in points:
        ilat, ilon = round(lat * 1e5), round(lon * 1e5)
        for d in (ilat - plat, ilon - plon):
            v = ~(d << 1) if d < 0 else d << 1
            while v >= 0x20:
                out.append(chr((0x20 | (v & 0x1F)) + 63))
                v >>= 5
            out.append(chr(v + 63))
        plat, plon = ilat, ilon
    return "".join(out)


def java_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    table = pq.read_table(sys.argv[1])
    geoms = shapely.from_wkb(table.column("geom").to_pylist())
    rows = table.drop(["geom"]).to_pylist()
    parts = defaultdict(list)
    for row, geom in zip(rows, geoms):
        parts[zone_of(row)].append(geom)
    to_wgs = Transformer.from_crs("EPSG:5179", "EPSG:4326", always_xy=True).transform
    zones, points = [], 0
    for (tariff, name), gs in sorted(parts.items()):
        merged = unary_union(gs).buffer(0).simplify(SIMPLIFY_M, preserve_topology=True)
        polys = sorted(getattr(merged, "geoms", [merged]), key=lambda p: -p.area)
        polys = [p for i, p in enumerate(polys) if i == 0 or p.area >= MIN_PART_M2]
        rings = []
        for p in polys:
            for ring in [p.exterior, *p.interiors]:
                xs, ys = to_wgs(*zip(*ring.coords[:-1]))
                pts = list(zip(xs, ys))   # the closing point repeats the first
                if len(pts) >= 3:
                    rings.append(polyline(pts))
                    points += len(pts)
        zones.append((tariff, name, " ".join(rings)))
    body = ",\n".join("        {" + java_string(t) + "," + java_string(n) + "," + java_string(r) + "}" for t, n, r in zones)
    TARGET.write_text(f'''// Generated by scripts/taxi_zones.py from {Path(sys.argv[1]).name}. Do not edit.
package com.veloster.vehicle;

/**
 * Taxi business areas: fare-table name (TaxiTariff), area name, and its rings as Google polyline strings separated by
 * spaces. Boundaries: Statistics Korea SGIS (https://sgis.kostat.go.kr, KOGL Type 1) as modified by vuski/admdongkor
 * (https://github.com/vuski/admdongkor, CC BY 4.0); simplified to {SIMPLIFY_M} m here.
 */
final class TaxiZoneData {{
    private TaxiZoneData(){{}}
    static final String[][] ZONES={{
{body}
    }};
}}
''', encoding="utf-8", newline="\n")
    print(f"{len(zones)} zones, {points} points, {TARGET.stat().st_size} bytes -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
